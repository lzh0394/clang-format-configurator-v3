// Downloads the clang-format wasm builds used by the app.
//
//   public/wasm/<version>/clang-format.{js,wasm}      runtime
//   public/wasm/<version>/clang-format-web.js         (22+, public API wrapper)
//   public/wasm/<version>/clang-format-binding.js     (22+)
//   public/wasm/<version>/entry.js                    generated shim, same API for all versions
//
// Idempotent: files whose sha256 matches tools/wasm.lock.json are skipped.
// The wasm binaries are deliberately NOT committed; the lock file keeps the
// download reproducible.
//
// Version notes (probed 2026-10-24):
//   16.x/17.x     no dump_config export -> schema defaults come from native
//   18.1.0-7      no dump_config export either (only 18.1.8+ has it)
//   18.1.8-21.x   single glue module, default init + named format/dump_config
//   22+/23.x      split package: the web entry wraps createModule + binding;
//                 dump_config works but emits shifted values (plan §3.1), so
//                 gen-schema gets those defaults from a native binary too

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { untar } from "./lib/tar.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const REGISTRY = process.env.NPM_REGISTRY ?? "https://registry.npmjs.org";
const LOCK_PATH = path.join(ROOT, "tools", "wasm.lock.json");

const ALWAYS = ["package/clang-format.js", "package/clang-format.wasm"];
const OPTIONAL = ["package/clang-format-binding.js", "package/clang-format-web.js"];

const args = process.argv.slice(2);
const force = args.includes("--force");
const only = args.find((arg) => arg.startsWith("--only="))?.slice("--only=".length);

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const sha512b64 = (buf) => createHash("sha512").update(buf).digest("base64");
const rel = (file) => path.relative(ROOT, file).replaceAll("\\", "/");

async function readJson(file, fallback) {
  if (!existsSync(file)) return fallback;
  return JSON.parse(await readFile(file, "utf8"));
}

function verifyIntegrity(buf, integrity) {
  if (!integrity?.startsWith("sha512-")) {
    throw new Error(`unsupported integrity field: ${integrity}`);
  }
  if (sha512b64(buf) !== integrity.slice("sha512-".length)) {
    throw new Error(`sha512 mismatch for ${integrity}`);
  }
}

async function upToDate(entry, lock) {
  const recorded = lock[entry.version];
  if (force || !recorded) return false;
  for (const file of Object.keys(recorded.files)) {
    const abs = path.join(ROOT, file);
    if (!existsSync(abs)) return false;
    if (sha256(await readFile(abs)) !== recorded.files[file]) return false;
  }
  return true;
}

function shim(api) {
  const entry = api === "web" ? "clang-format-web.js" : "clang-format.js";
  return [
    "// Generated by tools/fetch-wasm.mjs — do not edit.",
    `export * from "./${entry}";`,
    `export { default } from "./${entry}";`,
    "",
  ].join("\n");
}

async function fetchOne(entry, lock) {
  if (await upToDate(entry, lock)) {
    console.log(`  ${entry.version}  up to date`);
    return false;
  }

  const at = entry.pkg.lastIndexOf("@");
  const metaUrl = `${REGISTRY}/${entry.pkg.slice(0, at).replace("/", "%2F")}/${entry.pkg.slice(at + 1)}`;
  const meta = await fetch(metaUrl, { headers: { accept: "application/json" } });
  if (!meta.ok) throw new Error(`registry ${meta.status} for ${entry.pkg}`);
  const dist = (await meta.json()).dist;
  const tarball = await fetch(dist.tarball);
  if (!tarball.ok) throw new Error(`tarball ${tarball.status} for ${entry.pkg}`);
  const gz = Buffer.from(await tarball.arrayBuffer());
  verifyIntegrity(gz, dist.integrity);

  const archive = untar(gunzipSync(gz));
  const picked = [...ALWAYS, ...OPTIONAL.filter((name) => archive.has(name))];
  const missing = ALWAYS.filter((name) => !archive.has(name));
  if (missing.length) throw new Error(`${entry.pkg}: missing ${missing.join(", ")}`);

  const api = archive.has("package/clang-format-web.js") ? "web" : "legacy";
  const dir = path.join(ROOT, "public", "wasm", entry.version);
  await mkdir(dir, { recursive: true });

  const files = {};
  const write = async (name, data) => {
    const target = path.join(dir, name);
    await writeFile(target, data);
    files[rel(target)] = sha256(data);
  };
  for (const name of picked) await write(path.basename(name), archive.get(name));
  await write("entry.js", shim(api));

  lock[entry.version] = { integrity: dist.integrity, tarball: dist.tarball, api, files };
  console.log(`  ${entry.version}  ${api} api (${(gz.length / 1024 / 1024).toFixed(2)} MB tarball)`);
  return true;
}

const versions = JSON.parse(await readFile(path.join(ROOT, "tools", "versions.json"), "utf8"));
const selected = only ? versions.filter((v) => v.version === only) : versions;
if (selected.length === 0) throw new Error(`no version matched --only=${only}`);

const lock = await readJson(LOCK_PATH, {});
let changed = 0;
console.log(`fetch-wasm: ${selected.length} version(s) from ${REGISTRY}`);
for (const entry of selected) {
  if (await fetchOne(entry, lock)) changed += 1;
}

const sorted = Object.fromEntries(
  Object.keys(lock)
    .filter((key) => versions.some((entry) => entry.version === key))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .map((key) => [key, lock[key]]),
);
await writeFile(LOCK_PATH, `${JSON.stringify(sorted, null, 2)}\n`);
console.log(changed ? `fetch-wasm: ${changed} updated` : "fetch-wasm: nothing to do");
