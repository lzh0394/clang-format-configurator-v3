// Generates tests/golden/golden-21.1.8.json — the native side of the
// native-vs-wasm consistency check (plan.md §1, §8).
//
//   node tools/gen-golden.mjs                    # regenerate the committed JSON
//   node tools/gen-golden.mjs --check            # CI: fail on drift, write nothing
//   node tools/gen-golden.mjs --clang-format <path>
//
// Every `expected` value is the byte output of **native** clang-format 21.1.8
// for the fixture's `code` (stdin), `filename` (`--assume-filename=`) and
// `style` (`--style=<json>`). The browser e2e suite feeds the same three values
// to the wasm build and compares the output byte-for-byte — that comparison is
// the gate for "wasm behaves like native" and it only means something if the
// expectations are generated, never hand-edited.
//
// Binary resolution (first match wins):
//   1. --clang-format <path> argument
//   2. CLANG_FORMAT_BIN environment variable
//   3. `clang-format` on PATH (CI: `python -m pip install clang-format==21.1.8`)
//
// The version is hard-checked against 21.1.8: fixtures generated by a different
// native build are not comparable to the pinned wasm build.

