function fail(message) {
  console.error(`gen-golden: ${message}`);
  process.exit(1);
}

function usage() {
  console.log(`Generates ${RELATIVE_OUTPUT} from native clang-format ${VERSION}.

Usage:
  node tools/gen-golden.mjs [--check] [--clang-format <path>]

  --check                 Regenerate in memory and exit 1 if the committed
                          JSON differs (CI mode; writes nothing).
  --clang-format <path>   Native binary to use. Defaults to $CLANG_FORMAT_BIN,
                          then "clang-format" on PATH (if that is missing, the
                          binary cached under .cache/ for local runs is used).

Install the pinned native build with:
  ${PIP_HINT}`);
}

function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

function resolveBinary() {
  if (explicitBinary) return { binary: explicitBinary, source: "--clang-format" };
  const fromEnv = process.env.CLANG_FORMAT_BIN?.trim();
  if (fromEnv) return { binary: fromEnv, source: "CLANG_FORMAT_BIN" };
  return { binary: "clang-format", source: "PATH" };
}

/**
 * Runs `<binary> --version` and hard-fails unless it is exactly VERSION.
 *
 * Binary resolution is: --clang-format > CLANG_FORMAT_BIN > PATH. As a local
 * convenience only, when the implicit PATH lookup finds nothing, the 21.1.8
 * binary downloaded into this checkout's asset cache is used instead (CI always
 * resolves `clang-format` from PATH, so that branch never runs there).
 */
function locateNative() {
  const requested = resolveBinary();
  const attempt = spawnSync(requested.binary, ["--version"], { encoding: "utf8" });
  const parsed = parseVersionOutput(attempt);

  if (parsed.okay) {
    if (parsed.version !== VERSION) fail(versionMismatchMessage(requested.binary, requested.source, parsed.version));
    return { binary: requested.binary, source: requested.source, version: parsed.version };
  }

  const notFound = attempt.error?.code === "ENOENT";
  if (requested.source === "PATH" && notFound && existsSync(CACHED_BINARY)) {
    const cachedAttempt = spawnSync(CACHED_BINARY, ["--version"], { encoding: "utf8" });
    const cached = parseVersionOutput(cachedAttempt);
    if (cached.okay && cached.version === VERSION) {
      console.log(
        `note: clang-format is not on PATH; using the cached native binary at ${path
          .relative(ROOT, CACHED_BINARY)
          .split(path.sep)
          .join("/")}`,
      );
      return { binary: CACHED_BINARY, source: "repo cache", version: cached.version };
    }
  }

  const hints = [
    `native clang-format ${VERSION} could not be run (${requested.source}: ${requested.binary}): ${parsed.detail}`,
  ];
  if (notFound) {
    hints.push(
      `install it with: ${PIP_HINT}`,
      `or pass an existing binary: node tools/gen-golden.mjs --clang-format <path> (or set CLANG_FORMAT_BIN)`,
    );
  }
  fail(hints.join("\n"));
}

/** @returns {{okay: true, version: string} | {okay: false, detail: string}} */
function parseVersionOutput(result) {
  const stdout = (result.stdout ?? "").trim();
  if (result.error) return { okay: false, detail: result.error.message };
  if (result.status !== 0) {
    return { okay: false, detail: `--version exited with ${result.status}${stdout ? `: ${stdout}` : ""}` };
  }
  const match = /clang-format version (\S+)/.exec(stdout);
  if (!match) return { okay: false, detail: `could not parse the version from --version output: ${JSON.stringify(stdout)}` };
  return { okay: true, version: match[1] };
}

function versionMismatchMessage(binary, source, found) {
  return (
    `native clang-format is ${found} (${source}: ${binary}), but the golden fixtures must come from exactly ${VERSION}.\n` +
    `Install the pinned build with: ${PIP_HINT}\n` +
    `or pass the right binary via --clang-format / CLANG_FORMAT_BIN.`
  );
}

/** Formats one fixture through native clang-format; returns the exact output. */
function formatFixture(binary, fixture) {
  const result = spawnSync(
    binary,
    [`--assume-filename=${fixture.filename}`, `--style=${JSON.stringify(fixture.style)}`],
    {
      input: Buffer.from(fixture.code, "utf8"),
      maxBuffer: 32 * 1024 * 1024,
    },
  );

  if (result.error) {
    fail(`could not run clang-format for fixture "${fixture.name}": ${result.error.message}`);
  }
  if (result.status !== 0) {
    const stderr = (result.stderr ?? Buffer.alloc(0)).toString("utf8").trim();
    fail(
      `clang-format failed for fixture "${fixture.name}" (${fixture.filename}) with exit ${result.status}` +
        (stderr ? `:\n${stderr}` : ""),
    );
  }
  return result.stdout.toString("utf8");
}

/** Structural checks so the fixture set cannot silently lose coverage. */
function validateFixtures() {
  if (fixtures.length < 24) {
    fail(`at least 24 fixture groups are required (plan.md §1), found ${fixtures.length}`);
  }

  const names = new Set();
  const extensions = new Set();
  const styles = new Set();
  for (const fixture of fixtures) {
    const label = fixture?.name ?? "(unnamed fixture)";
    if (typeof fixture.name !== "string" || fixture.name.length === 0) fail("a fixture has no name");
    if (names.has(fixture.name)) fail(`duplicate fixture name: ${fixture.name}`);
    names.add(fixture.name);
    if (typeof fixture.filename !== "string" || fixture.filename.length === 0) {
      fail(`fixture "${label}" has no filename`);
    }
    if (typeof fixture.code !== "string") fail(`fixture "${label}" has no code string`);
    if (typeof fixture.style !== "object" || fixture.style === null || Array.isArray(fixture.style)) {
      fail(`fixture "${label}" must have a style object`);
    }
    if (typeof fixture.style.BasedOnStyle !== "string") {
      fail(`fixture "${label}" must set style.BasedOnStyle`);
    }
    styles.add(fixture.style.BasedOnStyle);
    extensions.add(path.extname(fixture.filename).toLowerCase());
  }

  for (const extension of REQUIRED_EXTENSIONS) {
    if (!extensions.has(extension)) fail(`no fixture uses a ${extension} file`);
  }
  for (const style of REQUIRED_STYLES) {
    if (!styles.has(style)) fail(`no fixture exercises the ${style} style`);
  }
}

function generate(binary) {
  return fixtures.map((fixture) => ({
    name: fixture.name,
    filename: fixture.filename,
    style: fixture.style,
    code: fixture.code,
    expected: formatFixture(binary, fixture),
  }));
}

function loadCommitted() {
  if (!existsSync(OUTPUT)) {
    fail(`${RELATIVE_OUTPUT} does not exist; run "node tools/gen-golden.mjs" to create it.`);
  }
  try {
    return JSON.parse(readFileSync(OUTPUT, "utf8"));
  } catch (error) {
    fail(`${RELATIVE_OUTPUT} is not valid JSON: ${error.message}`);
  }
}

/** Short "expected vs actual" excerpt around the first differing character. */
function diffSnippet(committed, generated) {
  const limit = Math.min(committed.length, generated.length);
  let index = 0;
  while (index < limit && committed[index] === generated[index]) index++;
  const start = Math.max(0, index - 30);
  const excerpt = (text) => JSON.stringify(text.slice(start, start + 90));
  return `expected ${excerpt(committed)}${index < committed.length ? "…" : ""} actual ${excerpt(generated)}${
    index < generated.length ? "…" : ""
  } at offset ${index}`;
}

/** Compares the committed payload to freshly generated fixtures (ignores generatedAt). */
function compareCommitted(committed, generated) {
  const problems = [];

  if (committed?.clangFormatVersion !== VERSION) {
    problems.push(
      `clangFormatVersion: committed ${JSON.stringify(committed?.clangFormatVersion)}, expected ${JSON.stringify(VERSION)}`,
    );
  }
  if (!Array.isArray(committed?.fixtures)) {
    problems.push("fixtures: missing or not an array");
    return problems;
  }

  const committedFixtures = committed.fixtures;
  const seen = new Set();
  for (const fixture of committedFixtures) {
    if (typeof fixture?.name === "string") seen.add(fixture.name);
  }
  for (const fixture of generated) {
    if (!seen.has(fixture.name)) problems.push(`missing fixture "${fixture.name}" (in generated set)`);
  }

  const max = Math.max(committedFixtures.length, generated.length);
  for (let index = 0; index < max; index++) {
    const expected = committedFixtures[index];
    const actual = generated[index];
    if (!expected) {
      problems.push(`unexpected extra committed fixture "${actual.name}" at index ${index}`);
      continue;
    }
    if (actual && expected.name !== actual.name) {
      problems.push(`fixture order changed at index ${index}: committed "${expected.name}", generated "${actual.name}"`);
      continue;
    }
    if (!actual) {
      problems.push(`committed fixture "${expected.name}" no longer exists in the generator`);
      continue;
    }
    if (expected.filename !== actual.filename) {
      problems.push(`fixture "${actual.name}": filename ${JSON.stringify(expected.filename)} != ${JSON.stringify(actual.filename)}`);
    }
    if (JSON.stringify(expected.style) !== JSON.stringify(actual.style)) {
      problems.push(`fixture "${actual.name}": style ${JSON.stringify(expected.style)} != ${JSON.stringify(actual.style)}`);
    }
    if (typeof expected.code !== "string" || expected.code !== actual.code) {
      problems.push(`fixture "${actual.name}": code differs from the generator`);
    }
    if (typeof expected.expected !== "string") {
      problems.push(`fixture "${actual.name}": expected output is missing`);
    } else if (expected.expected !== actual.expected) {
      problems.push(`fixture "${actual.name}": expected output drifted — ${diffSnippet(expected.expected, actual.expected)}`);
    }
  }

  return problems;
}

