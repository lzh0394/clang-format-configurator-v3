const args = process.argv.slice(2);
let check = false;
let explicitBinary = null;

for (let index = 0; index < args.length; index++) {
  const arg = args[index];
  if (arg === "--check") {
    check = true;
  } else if (arg === "--clang-format") {
    const value = args[++index];
    if (!value) fail("--clang-format needs a path");
    explicitBinary = value;
  } else if (arg.startsWith("--clang-format=")) {
    explicitBinary = arg.slice("--clang-format=".length);
    if (!explicitBinary) fail("--clang-format needs a path");
  } else if (arg === "--help" || arg === "-h") {
    usage();
    process.exit(0);
  } else {
    fail(`unknown argument "${arg}" (try --help)`);
  }
}

const native = locateNative();
console.log(`native clang-format ${native.version} (${native.source}: ${native.binary})`);

validateFixtures();
const generated = generate(native.binary);
const payload = {
  clangFormatVersion: VERSION,
  generatedAt: new Date().toISOString(),
  fixtures: generated,
};
const serialized = `${JSON.stringify(payload, null, 2)}\n`;

if (check) {
  const committed = loadCommitted();
  const problems = compareCommitted(committed, generated);
  if (problems.length > 0) {
    const shown = problems.slice(0, 8);
    const more = problems.length - shown.length;
    fail(
      `golden fixtures in ${RELATIVE_OUTPUT} are out of date:\n  - ${shown.join("\n  - ")}` +
        (more > 0 ? `\n  - … and ${more} more problem(s)` : "") +
        `\nRegenerate with the same native clang-format ${VERSION}: node tools/gen-golden.mjs`,
    );
  }
  const committedBytes = readFileSync(OUTPUT).byteLength;
  console.log(`golden fixtures: ${generated.length} groups up to date (${RELATIVE_OUTPUT}, ${kb(committedBytes)})`);
} else {
  mkdirSync(path.dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, serialized);
  console.log(`wrote ${RELATIVE_OUTPUT}: ${generated.length} fixture groups, ${kb(Buffer.byteLength(serialized))}`);
}
